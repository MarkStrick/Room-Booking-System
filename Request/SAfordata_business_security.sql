-- Shared statement gate locks before row locks, including API/worker/admin writes.
-- Safety first: serialize these writes just as the current PostgreSQL adapter does.
DECLARE v_table VARCHAR2(128);v_trigger VARCHAR2(128);
BEGIN
 FOR r IN(SELECT 'BOOKING' t FROM dual UNION ALL SELECT 'BOOKING_EQUIPMENT' FROM dual
  UNION ALL SELECT 'ROOM_CLOSURE' FROM dual UNION ALL SELECT 'HOLIDAY' FROM dual
  UNION ALL SELECT 'PENALTY' FROM dual UNION ALL SELECT 'ROOM_ASSIGNMENT' FROM dual
  UNION ALL SELECT 'ROOM' FROM dual UNION ALL SELECT 'USERS' FROM dual UNION ALL SELECT 'STAFF' FROM dual
  UNION ALL SELECT 'EQUIPMENT' FROM dual UNION ALL SELECT 'BOOKING_PARTICIPANT' FROM dual) LOOP
  v_table:=DBMS_ASSERT.SIMPLE_SQL_NAME(r.t);
  v_trigger:=DBMS_ASSERT.SIMPLE_SQL_NAME('gate_'||r.t);
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRIGGER '||v_trigger||' BEFORE INSERT OR UPDATE OR DELETE ON '||v_table||
   ' DECLARE v_id NUMBER; BEGIN SELECT id INTO v_id FROM kku_app_lock WHERE id=1 FOR UPDATE; END;';
 END LOOP;
END;
