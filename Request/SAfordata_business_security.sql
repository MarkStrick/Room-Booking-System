-- Release in AFTER STATEMENT: child triggers may safely read booking there.
CREATE OR REPLACE TRIGGER trg_booking_release_stock
FOR UPDATE OF booking_status ON booking COMPOUND TRIGGER
 TYPE ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;g_ids ids;
 AFTER EACH ROW IS BEGIN
  IF :OLD.booking_status IN('PENDING','APPROVED','CHECKED_IN') AND :NEW.booking_status IN('REJECTED','CANCELLED','COMPLETED','NO_SHOW') THEN
   g_ids(g_ids.COUNT+1):=:NEW.booking_id;
  END IF;
 END AFTER EACH ROW;
 AFTER STATEMENT IS BEGIN
  FOR i IN 1..g_ids.COUNT LOOP
   UPDATE booking_equipment SET released_qty=borrowed_qty-issued_qty WHERE booking_booking_id=g_ids(i);
  END LOOP;
 END AFTER STATEMENT;
END;
