CREATE OR REPLACE TRIGGER trg_booking_no_overlap FOR INSERT OR UPDATE ON booking COMPOUND TRIGGER
 TYPE slot IS RECORD(bid NUMBER,uid NUMBER,rid NUMBER,s TIMESTAMP,e TIMESTAMP,status VARCHAR2(50));
 TYPE slots IS TABLE OF slot INDEX BY PLS_INTEGER;g_slots slots;
 AFTER EACH ROW IS n PLS_INTEGER; BEGIN
  IF :NEW.booking_status IN('PENDING','APPROVED','CHECKED_IN') THEN
   n:=g_slots.COUNT+1;g_slots(n).bid:=:NEW.booking_id;g_slots(n).uid:=:NEW.users_user_id;g_slots(n).rid:=:NEW.room_room_id;
   g_slots(n).s:=:NEW.start_time;g_slots(n).e:=:NEW.end_time;g_slots(n).status:=:NEW.booking_status;
  END IF;
 END AFTER EACH ROW;
 AFTER STATEMENT IS v_count NUMBER; BEGIN
  FOR i IN 1..g_slots.COUNT LOOP
   SELECT COUNT(*) INTO v_count FROM booking WHERE room_room_id=g_slots(i).rid AND booking_id<>g_slots(i).bid
    AND booking_status IN('PENDING','APPROVED','CHECKED_IN') AND start_time<g_slots(i).e AND end_time>g_slots(i).s;
   IF v_count>0 THEN RAISE_APPLICATION_ERROR(-20001,'Overlapping booking'); END IF;
   SELECT COUNT(*) INTO v_count FROM booking WHERE users_user_id=g_slots(i).uid AND booking_status='PENDING';
   IF v_count>3 THEN RAISE_APPLICATION_ERROR(-20007,'Maximum three pending requests per user'); END IF;
  END LOOP;
 END AFTER STATEMENT;
END;
