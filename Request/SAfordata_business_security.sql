CREATE OR REPLACE TRIGGER trg_be_stock
BEFORE INSERT OR DELETE OR UPDATE ON booking_equipment FOR EACH ROW
DECLARE v_status booking.booking_status%TYPE;v_delta NUMBER;
BEGIN
 IF DELETING THEN RAISE_APPLICATION_ERROR(-20006,'Keep loan history; close booking and record returns instead'); END IF;
 SELECT booking_status INTO v_status FROM booking WHERE booking_id=:NEW.booking_booking_id;
 IF INSERTING THEN
  IF v_status NOT IN('PENDING','APPROVED') OR :NEW.issued_qty<>0 OR :NEW.returned_qty<>0 OR :NEW.released_qty<>0 THEN
   RAISE_APPLICATION_ERROR(-20006,'New loan must be an unissued active reservation');
  END IF;
  UPDATE equipment SET remaining_qty=remaining_qty-:NEW.borrowed_qty,updated_at=SYSTIMESTAMP
   WHERE equipment_id=:NEW.equipment_equipment_id AND remaining_qty>=:NEW.borrowed_qty AND is_deleted=0
     AND equipment_status='AVAILABLE' AND usage_type IN('BORROWABLE','BOTH');
  IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20005,'Insufficient borrowable equipment'); END IF;
 ELSE
  IF :NEW.booking_booking_id<>:OLD.booking_booking_id OR :NEW.equipment_equipment_id<>:OLD.equipment_equipment_id OR :NEW.borrowed_qty<>:OLD.borrowed_qty THEN
   RAISE_APPLICATION_ERROR(-20006,'Loan identity and reserved quantity are immutable');
  END IF;
  IF :NEW.issued_qty<:OLD.issued_qty OR :NEW.returned_qty<:OLD.returned_qty OR :NEW.released_qty<:OLD.released_qty THEN
   RAISE_APPLICATION_ERROR(-20006,'Loan counters cannot decrease');
  END IF;
  IF :NEW.issued_qty>:OLD.issued_qty AND v_status<>'CHECKED_IN' THEN RAISE_APPLICATION_ERROR(-20006,'Issue only after check-in'); END IF;
  IF :NEW.released_qty>:OLD.released_qty AND v_status IN('PENDING','APPROVED','CHECKED_IN') THEN RAISE_APPLICATION_ERROR(-20006,'Release only when booking is closed'); END IF;
  v_delta:=:NEW.returned_qty-:OLD.returned_qty+:NEW.released_qty-:OLD.released_qty;
  IF v_delta>0 THEN UPDATE equipment SET remaining_qty=remaining_qty+v_delta,updated_at=SYSTIMESTAMP WHERE equipment_id=:NEW.equipment_equipment_id; END IF;
 END IF;
 -- Movement rows are written in AFTER ROW below, after the parent loan exists.
END;
/
CREATE OR REPLACE TRIGGER trg_be_movement AFTER INSERT OR UPDATE ON booking_equipment FOR EACH ROW
DECLARE v_prefix VARCHAR2(100);
 PROCEDURE movement(p_type VARCHAR2,p_qty NUMBER,p_total NUMBER) IS
 BEGIN
  INSERT INTO stock_movement(booking_id,equipment_id,movement_type,quantity,source_event_key)
   VALUES(:NEW.booking_booking_id,:NEW.equipment_equipment_id,p_type,p_qty,v_prefix||p_type||':'||TO_CHAR(p_total,'FM9999999990'));
 END;
BEGIN
 v_prefix:=TO_CHAR(:NEW.booking_booking_id,'FM9999999990')||':'||TO_CHAR(:NEW.equipment_equipment_id,'FM9999999990')||':';
 IF INSERTING THEN movement('RESERVE',:NEW.borrowed_qty,:NEW.borrowed_qty);
 ELSE
  IF :NEW.issued_qty>:OLD.issued_qty THEN movement('ISSUE',:NEW.issued_qty-:OLD.issued_qty,:NEW.issued_qty); END IF;
  IF :NEW.returned_qty>:OLD.returned_qty THEN movement('RETURN',:NEW.returned_qty-:OLD.returned_qty,:NEW.returned_qty); END IF;
  IF :NEW.released_qty>:OLD.released_qty THEN movement('RELEASE',:NEW.released_qty-:OLD.released_qty,:NEW.released_qty); END IF;
 END IF;
END;
