CREATE OR REPLACE TRIGGER trg_booking_rules BEFORE INSERT OR UPDATE ON booking FOR EACH ROW
DECLARE v_count NUMBER;v_capacity NUMBER;v_user NUMBER;v_now TIMESTAMP:=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP);
BEGIN
 IF INSERTING THEN
  IF :NEW.booking_status<>'PENDING' THEN RAISE_APPLICATION_ERROR(-20007,'New booking must be PENDING'); END IF;
  IF :NEW.start_time<=v_now OR :NEW.start_time>v_now+INTERVAL '15' DAY THEN RAISE_APPLICATION_ERROR(-20007,'Booking must start within the next 15 days'); END IF;
  :NEW.approval_deadline:=CAST(:NEW.created_at AS TIMESTAMP)+INTERVAL '4' HOUR;
 ELSE
  IF :NEW.users_user_id<>:OLD.users_user_id OR :NEW.room_room_id<>:OLD.room_room_id OR :NEW.start_time<>:OLD.start_time OR :NEW.end_time<>:OLD.end_time THEN
   RAISE_APPLICATION_ERROR(-20007,'Cancel and create a new booking to change its owner, room or slot');
  END IF;
  IF :NEW.booking_status<>:OLD.booking_status AND NOT(
   (:OLD.booking_status='PENDING' AND :NEW.booking_status IN('APPROVED','REJECTED','CANCELLED')) OR
   (:OLD.booking_status='APPROVED' AND :NEW.booking_status IN('CHECKED_IN','CANCELLED','NO_SHOW')) OR
   (:OLD.booking_status='CHECKED_IN' AND :NEW.booking_status='COMPLETED')) THEN
   RAISE_APPLICATION_ERROR(-20007,'Invalid booking transition');
  END IF;
  :NEW.version:=:OLD.version+1;
 END IF;
 :NEW.updated_at:=SYSTIMESTAMP;
 IF :NEW.booking_status IN('PENDING','APPROVED','CHECKED_IN') THEN
  SELECT COUNT(*),MAX(capacity) INTO v_count,v_capacity FROM room WHERE room_id=:NEW.room_room_id AND is_deleted=0 AND room_status='AVAILABLE';
  IF v_count=0 OR :NEW.expected_attendees>v_capacity THEN RAISE_APPLICATION_ERROR(-20007,'Room unavailable or over capacity'); END IF;
  SELECT COUNT(*) INTO v_count FROM holiday WHERE holiday_date=TRUNC(:NEW.booking_date);
  IF v_count>0 THEN RAISE_APPLICATION_ERROR(-20002,'Room unavailable on holiday'); END IF;
  SELECT COUNT(*) INTO v_count FROM room_closure WHERE room_id=:NEW.room_room_id AND start_at<:NEW.end_time AND end_at>:NEW.start_time;
  IF v_count>0 THEN RAISE_APPLICATION_ERROR(-20007,'Room closed in this interval'); END IF;
 END IF;
 IF INSERTING OR (:NEW.booking_status='CHECKED_IN' AND :OLD.booking_status<>'CHECKED_IN') THEN
  SELECT COUNT(*) INTO v_count FROM users WHERE user_id=:NEW.users_user_id AND is_deleted=0 AND account_status='ACTIVE';
  IF v_count=0 THEN RAISE_APPLICATION_ERROR(-20003,'Account unavailable'); END IF;
  SELECT COUNT(*) INTO v_count FROM penalty WHERE users_user_id=:NEW.users_user_id AND penalty_type='SUSPENSION' AND penalty_status='ACTIVE'
   AND (start_date IS NULL OR start_date<=TRUNC(CAST(v_now AS DATE))) AND (end_date IS NULL OR end_date>=TRUNC(CAST(v_now AS DATE)));
  IF v_count>0 THEN RAISE_APPLICATION_ERROR(-20003,'Active suspension'); END IF;
 END IF;
 IF UPDATING AND :NEW.booking_status IN('APPROVED','REJECTED') AND :OLD.booking_status<>:NEW.booking_status THEN
  v_user:=:NEW.decided_actor_user_id;
  IF v_user IS NULL AND :NEW.staff_staff_id IS NOT NULL THEN SELECT users_user_id INTO v_user FROM staff WHERE staff_id=:NEW.staff_staff_id; END IF;
  SELECT COUNT(*) INTO v_count FROM users u WHERE u.user_id=v_user AND u.account_status='ACTIVE' AND u.is_deleted=0 AND (
   u.role_level='ADMIN' OR (u.role_level='STAFF' AND EXISTS(
    SELECT 1 FROM staff s JOIN room_assignment a ON a.staff_staff_id=s.staff_id
     WHERE s.users_user_id=u.user_id AND s.staff_status='ACTIVE' AND a.room_room_id=:NEW.room_room_id AND a.assignment_status='ACTIVE'
      AND (a.start_date IS NULL OR a.start_date<=TRUNC(CAST(v_now AS DATE))) AND (a.end_date IS NULL OR a.end_date>=TRUNC(CAST(v_now AS DATE))))));
  IF v_count=0 THEN RAISE_APPLICATION_ERROR(-20004,'Actor lacks current room assignment or admin role'); END IF;
  :NEW.decided_actor_user_id:=v_user;
 END IF;
END;
